def pizz_note(midi, vel, rng):
    f0 = mtof(midi)
    L = int(1.4 * SR)
    t = np.arange(L) / SR
    y = np.zeros(L)
    for n in range(1, 24):
        fn = n * f0 * (1 + 0.0004 * n * n)
        if fn > 7000:
            break
        a = n ** -1.25 * math.exp(-fn / (1400 + 2200 * vel))
        tau = 0.42 / (1 + 0.28 * (n - 1))
        y += a * np.exp(-t / tau) * np.sin(TWO_PI * fn * t + rng.random() * 0.4)
    y[: int(0.0012 * SR)] *= np.linspace(0, 1, int(0.0012 * SR))
    y = filt(peaking(300, 1.2, 4.0), y)
    y = filt(hp(90), y)
    return fade_edges(y * vel * 0.35, 0.0, 0.05)


def sub_note(midi, dur, vel, att=0.006, decay=0.6, sustain=0.45, rel=0.12):
    f0 = mtof(midi)
    while f0 < 38:
        f0 *= 2
    L = int((dur + rel) * SR)
    t = np.arange(L) / SR
    x = np.sin(TWO_PI * f0 * t)
    x = np.tanh(1.4 * x) / np.tanh(1.4)           # warm 3rd harmonic
    x += 0.18 * np.sin(TWO_PI * 2 * f0 * t)        # gentle 2nd for small speakers
    env = smoothstep(t / att) * (sustain + (1 - sustain) * np.exp(-t / decay))
    env *= 0.5 + 0.5 * np.cos(np.pi * np.clip((t - dur) / rel, 0, 1))
    return fade_edges(x * env * vel, 0.0, 0.01)


def sub(t0, name, dur, vel, **kw):
    add("bass", t0, sub_note(M(name), dur, vel, **kw))


def drum(vel, pitch, size, rng, slap=1.0):
    """Taiko / tom: swept sine body + membrane modes + stick slap + thud."""
    L = int((0.9 + 0.9 * size) * SR)
    t = np.arange(L) / SR
    fe = 60.0 * pitch
    f = fe + (fe * 1.25) * np.exp(-t / 0.022)
    body = np.sin(TWO_PI * np.cumsum(f) / SR) * np.exp(-t / (0.38 * size))
    modes = np.zeros(L)
    for r, a, d in zip([1.59, 2.14, 2.30, 2.65, 2.92, 3.16, 3.50],
                       [.45, .32, .26, .2, .15, .11, .08],
                       [.2, .15, .13, .1, .085, .075, .06]):
        fm = fe * r * (1 + 0.04 * np.exp(-t / 0.03))
        modes += a * np.sin(TWO_PI * np.cumsum(fm) / SR) * np.exp(-t / (d * size))
    nl = int(0.12 * SR)
    tn = np.arange(nl) / SR
    sl = filt(bp(500, 3200), rng.standard_normal(nl)) * np.exp(-tn / 0.005) * 0.55 * slap
    th = filt(lp(160), rng.standard_normal(nl)) * np.exp(-tn / 0.045) * 2.5
    x = body + 0.6 * modes
    x[:nl] += sl + th
    x = np.tanh(1.5 * x * vel) / np.tanh(1.5)
    x[: int(0.0004 * SR)] *= np.linspace(0, 1, int(0.0004 * SR))
    return fade_edges(x, 0.0, 0.05)


def DP(note):
    """Drum pitch factor that tunes the drum body (60 Hz * factor) to a note."""
    return mtof(M(note)) / 60.0


def hit(t0, kind, vel, pitch, size, p=0.0, gain=1.0, slap=1.3):
    rng = rng_for("drum", round(t0 * 1000), kind)
    add("perc", t0, drum(vel, pitch, size, rng, slap), p=p, gain=gain)
    event(kind, t0, vel=round(vel, 3))


def cymbal(L_sec, rng, decay=1.8):
    L = int(L_sec * SR)
    t = np.arange(L) / SR
    nz = rng.standard_normal((2, L))
    wash = filt(lp(10500, 2), filt(hp(3200, 2), nz)) * np.exp(-t / decay)
    body = filt(bp(700, 2400), nz[::-1]) * np.exp(-t / (decay * 0.35)) * 0.35
    shimmer = np.zeros((2, L))
    for _ in range(70):
        f = math.exp(rng.uniform(math.log(2200), math.log(8500)))
        a = rng.uniform(0.2, 1.0) * 0.012
        d = rng.uniform(0.5, 1.0) * decay
        ch = rng.integers(0, 2)
        shimmer[ch] += a * np.sin(TWO_PI * f * t + rng.random() * 6.3) * np.exp(-t / d)
    y = wash + body + shimmer
    y[:, : int(0.001 * SR)] *= np.linspace(0, 1, int(0.001 * SR))
    return fade_edges(y, 0.0, 0.05)


def impact_sig(size, rng, root_hz=None):
    """Cinematic impact: sub drop + boom + multiband noise burst + metal tail."""
    L = int(5.0 * SR)
    t = np.arange(L) / SR
    root_hz = root_hz or mtof(M("D2"))
    f_end = root_hz / 2 if root_hz / 2 >= 34 else root_hz   # land on the bass note (>= 34 Hz)
    f = f_end + 45 * np.exp(-t / 0.32)
    subd = np.sin(TWO_PI * np.cumsum(f) / SR) * np.exp(-t / (0.9 * size)) * 0.9
    boom = np.zeros(L)
    b = drum(1.0, root_hz / 60.0, 1.7 * size, rng, slap=0.9)
    boom[: len(b)] = b
    nz = rng.standard_normal((2, L))
    burst = (filt(hp(2200), nz) * np.exp(-t / 0.05) * 0.25
             + filt(bp(250, 2200), nz) * np.exp(-t / 0.17) * 0.55
             + filt(lp(260), nz) * np.exp(-t / 0.45) * 0.9)
    metal = np.zeros((2, L))
    for _ in range(34):
        fr = math.exp(rng.uniform(math.log(240), math.log(3400)))
        a = rng.uniform(0.3, 1.0) * 0.05 / math.sqrt(fr / 240)
        d = rng.uniform(1.0, 2.8) * size
        pan = rng.uniform(-1, 1)
        s = a * np.sin(TWO_PI * fr * (t - 0.004 * t * t) + rng.random() * 6.3) * np.exp(-t / d)
        s *= smoothstep(t / 0.012)
        metal[0] += s * (1 - pan) * 0.5
        metal[1] += s * (1 + pan) * 0.5
    mono = subd + 0.9 * boom
    y = np.vstack([mono, mono]) + burst + metal
    y = np.tanh(1.2 * y) / np.tanh(1.2)
    y[:, : int(0.0005 * SR)] *= np.linspace(0, 1, int(0.0005 * SR))
    return fade_edges(y, 0.0, 0.2)


def bass_hz(t):
    """Bass note of the chord sounding at t, folded into 45-90 Hz (drum tuning)."""
    f = mtof(M(V[chord_at(t)][0]))
    while f < 45:
        f *= 2
    while f > 90:
        f /= 2
    return f


def impact(t0, kind, size=1.0, gain=1.0):
    sig = impact_sig(size, rng_for("imp", round(t0 * 1000)), bass_hz(t0 + 0.01))
    add("impact", t0, sig, gain=gain)
    event(kind, t0, size=size)


def stft_filter(x, gain_fn, nper=2048, hop=256):
    _, tt, Z = stft(x, fs=SR, nperseg=nper, noverlap=nper - hop)
    ff = np.fft.rfftfreq(nper, 1 / SR)
    G = gain_fn(ff[:, None], tt[None, :])
    _, y = istft(Z * G, fs=SR, nperseg=nper, noverlap=nper - hop)
    return y[..., : x.shape[-1]]


def riser_sig(length, rng):
    L = int(length * SR)
    nz = rng.standard_normal((2, L))

    def g(f, tt):
        u = np.clip(tt / length, 0, 1)
        fc = 350 * (24 ** (u ** 1.4))                   # 350 Hz -> 8.4 kHz
        oc = np.log2(np.maximum(f, 20) / fc)
        return np.exp(-0.5 * (oc / 0.75) ** 2) + 0.04 * (f < 9000)

    y = stft_filter(nz, g)
    t = np.arange(L) / SR
    u = t / length
    trem = 1 - 0.06 * (0.5 + 0.5 * np.sin(TWO_PI * np.cumsum(3 + 11 * u ** 2) / SR))
    y *= (u ** 2.3) * trem
    y = filt(lp(11000, 4), y)
    return fade_edges(y, 0.05, 0.002)


# --------------------------------------------------------------------------
# reverb: decorrelated stereo noise IR, band-dependent decay + early reflections
# --------------------------------------------------------------------------
def make_ir(rt, length, predelay, rng, n_er=14, er_span=0.07):
    L = int(length * SR)
    t = np.arange(L) / SR
    bands = [(20, 180, 1.15), (180, 500, 1.05), (500, 1200, 1.0), (1200, 2800, 0.85),
             (2800, 6000, 0.62), (6000, 12000, 0.42), (12000, 20000, 0.25)]
    ir = np.zeros((2, L))
    for ch in range(2):
        nz = rng.standard_normal(L)
        for lo, hi, k in bands:
            if lo <= 20:
                band = filt(lp(hi, 4), nz)
            elif hi >= 20000:
                band = filt(hp(lo, 4), nz)
            else:
                band = filt(bp(lo, hi, 2), nz)
            ir[ch] += band * np.exp(-6.9078 * t / (rt * k))
    ir *= smoothstep((t - predelay) / 0.03)          # late field fades in
    ir /= np.sqrt(np.sum(ir ** 2) / 2)
    # early reflections (sparse taps, alternating sides, slightly darkened)
    er = np.zeros((2, L))
    for i in range(n_er):
        d = predelay * 0.4 + rng.uniform(0.004, er_span)
        a = 0.55 * math.exp(-d / 0.05) * rng.uniform(0.5, 1.0)
        ch = i % 2
        er[ch, S(d)] += a * (1 if rng.random() > 0.3 else -1)
    er = filt(lp(7000), er)
    return ir + er


def convolve_stereo(x, ir):
    m = 0.5 * (x[0] + x[1])
    yl = fftconvolve(0.7 * x[0] + 0.3 * m, ir[0])[: x.shape[1]]
    yr = fftconvolve(0.7 * x[1] + 0.3 * m, ir[1])[: x.shape[1]]
    return np.vstack([yl, yr])


def sympathetic_ir(rng):
    """Undamped piano strings as a resonator bank (sustain pedal down)."""
    L = int(3.0 * SR)
    t = np.arange(L) / SR
    ir = np.zeros((2, L))
    for m in range(28, 100):
        f = mtof(m)
        for n in range(1, 6):
            fn = n * f
            if fn > 6000:
                break
            tau = 1.6 * 2 ** (-(m - 50) / 24) / n
            ir[m % 2] += (1 / n) * np.sin(TWO_PI * fn * t + rng.random() * 6.3) * np.exp(-t / tau)
    ir *= smoothstep(t / 0.01)
    return ir / np.sqrt(np.sum(ir ** 2) / 2)


