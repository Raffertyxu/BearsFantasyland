def add(name, t0, sig, p=0.0, gain=1.0):
    """Add a mono (L,) or stereo (2,L) signal to a bus at time t0 (s)."""
    s0 = S(t0)
    if sig.ndim == 1:
        gl, gr = pan_gains(p)
        sig = np.vstack([sig * gl, sig * gr])
    L = sig.shape[1]
    if s0 < 0:
        sig = sig[:, -s0:]
        L += s0
        s0 = 0
    e = min(NT, s0 + L)
    bus[name][:, s0:e] += gain * sig[:, : e - s0]


def event(kind, t, **kw):
    d = {"t": round(float(t), 6), "sample": S(t), "type": kind}
    d.update(kw)
    EVENTS.append(d)


