def piano_note(midi, vel, hold, rng):
    """Felt piano: inharmonic partials, two detuned strings, per-partial
    two-stage decay, velocity-dependent brightness, felt hammer thump."""
    f0 = mtof(midi)
    tau0 = float(np.clip(7.5 * 2 ** (-(midi - 45) / 15.0), 0.9, 9.0))
    L = int(SR * min(hold + 0.45, 5.0 * tau0 + 0.3))
    t = np.arange(L) / SR
    B = 0.00007 * 2 ** ((midi - 40) / 13.0)          # inharmonicity
    fc = 650 + 3600 * vel ** 1.8                      # felt brightness
    hpos = 0.115 + 0.02 * rng.random()                # hammer position
    det = 2 ** ((0.35 + 0.9 * rng.random()) / 1200)  # unison detune
    out = np.zeros((2, L))
    for n in range(1, 60):
        fn = n * f0 * math.sqrt(1 + B * n * n)
        if fn > 14000 or fn > fc * 5:
            break
        a = n ** -1.05 * math.exp(-((fn / fc) ** 1.35)) * (0.22 + abs(math.sin(math.pi * n * hpos)))
        if a < 3e-4:
            continue
        tau = tau0 / (1 + 0.09 * (n - 1)) / (1 + (fn / 2600) ** 1.25)
        env = 0.58 * np.exp(-t / (tau * 0.2)) + 0.42 * np.exp(-t / tau)
        p1, p2 = rng.random(2) * TWO_PI
        s1 = np.sin(TWO_PI * fn * t + p1)
        s2 = np.sin(TWO_PI * fn * det * t + p2)
        out[0] += a * env * (0.6 * s1 + 0.4 * s2)
        out[1] += a * env * (0.4 * s1 + 0.6 * s2)
    # attack: felt hammer contact time (softer = slower)
    att = int(SR * (0.0015 + 0.003 * (1 - vel)))
    out[:, :att] *= np.sin(0.5 * np.pi * np.arange(att) / att) ** 2
    # felt thump + soundboard knock
    nl = min(L, int(0.09 * SR))
    tn = np.arange(nl) / SR
    nz = filt(lp(220 + 1600 * vel), rng.standard_normal(nl)) * np.exp(-tn / 0.011)
    knock = np.sin(TWO_PI * (88 + 30 * rng.random()) * tn) * np.exp(-tn / 0.03)
    thump = (0.10 * nz + 0.035 * knock) * vel
    thump[: int(0.0015 * SR)] *= np.linspace(0, 1, int(0.0015 * SR))
    out[:, :nl] += thump
    # damper (felt, a little slow) after the hold time
    if hold < L / SR:
        h = S(hold)
        out[:, h:] *= np.exp(-np.arange(L - h) / SR / 0.085)
    out *= (0.18 + 0.82 * vel ** 1.45) * 0.22
    return fade_edges(out, 0.0, 0.03)


def piano(t0, name_or_midi, vel, hold, tag="pn", record=None):
    midi = M(name_or_midi) if isinstance(name_or_midi, str) else name_or_midi
    rng = rng_for(tag, round(t0 * 1000), midi)
    sig = piano_note(midi, vel, hold, rng)
    w = float(np.clip((midi - 62) / 30.0, -0.45, 0.45))   # player's perspective
    gl, gr = pan_gains(w)
    sig[0] *= gl * 1.4142
    sig[1] *= gr * 1.4142
    add("piano", t0, sig)
    if record:
        event(record[0], t0, note=name_or_midi if isinstance(name_or_midi, str) else midi, **record[1])


