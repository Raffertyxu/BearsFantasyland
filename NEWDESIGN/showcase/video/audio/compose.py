def string_note(sec, midi, dur, vel, att, rel, rng):
    nv, spread, vib, p, width, hpf, (fd, fb), body = SECTIONS[sec]
    f0 = mtof(midi)
    L = int((dur + rel + 0.05) * SR)
    t = np.arange(L) / SR
    out = np.zeros((2, L))
    for v in range(nv):
        x = (v / (nv - 1)) * 2 - 1
        cents = x * spread + rng.normal(0, 1.2)
        rate = rng.uniform(4.7, 5.8)
        depth = vib * rng.uniform(0.7, 1.15) * smoothstep((t - rng.uniform(0.25, 0.45)) / 0.7)
        drift = 2.0 * np.sin(TWO_PI * rng.uniform(0.07, 0.3) * t + rng.random() * 6.3) \
            + 1.2 * np.sin(TWO_PI * rng.uniform(0.3, 0.8) * t + rng.random() * 6.3)
        c = cents + depth * np.sin(TWO_PI * rate * t + rng.random() * 6.3) + drift
        saw = polyblep_saw(f0 * 2 ** (c / 1200), rng.random())
        gl, gr = pan_gains(p + width * x * 0.5)
        out[0] += saw * gl
        out[1] += saw * gr
    out /= math.sqrt(nv)
    # amplitude envelope: slow bow attack, gentle swell, smooth release
    a = smoothstep(t / att) ** 0.8
    r = 0.5 + 0.5 * np.cos(np.pi * np.clip((t - dur) / rel, 0, 1))
    env = a * r * (1 + 0.08 * smoothstep((t - att) / max(dur - att, 0.1)))
    # dynamic brightness: crossfade dark/bright low-pass by envelope*velocity
    dark = filt(lp(fd, 4), out)
    bright = filt(lp(fb, 4), out)
    k = np.clip(env * (0.25 + 0.75 * vel), 0, 1)
    y = dark + (bright - dark) * k
    # bow hair noise: band-limited, follows the bow pressure (stronger on attack)
    bow = filt(bp(f0 * 2.5, min(f0 * 9, 3000)), rng.standard_normal((2, L)))
    y += bow * (0.05 + 0.10 * np.exp(-t / 0.12)) * (0.4 + 0.6 * vel)
    for (f, q, g) in body:
        y = filt(peaking(f, q, g), y)
    y = filt(hp(hpf), y)
    return fade_edges(y * env * vel, 0.003, 0.03)


