def k_weight(x):
    s1 = np.array([[1.53512485958697, -2.69169618940638, 1.19839281085285,
                    1.0, -1.69065929318241, 0.73248077421585]])
    s2 = np.array([[1.0, -2.0, 1.0, 1.0, -1.99004745483398, 0.99007225036621]])
    return sosfilt(s2, sosfilt(s1, x, axis=-1), axis=-1)


def lufs(x):
    y = k_weight(x)
    blk, hop = int(0.4 * SR), int(0.1 * SR)
    p = np.array([np.mean(y[:, i:i + blk] ** 2, axis=1).sum()
                  for i in range(0, y.shape[1] - blk + 1, hop)])
    lk = -0.691 + 10 * np.log10(p + 1e-20)
    p = p[lk > -70]
    rel = -0.691 + 10 * np.log10(p.mean()) - 10
    p = p[(-0.691 + 10 * np.log10(p)) > rel]
    return -0.691 + 10 * np.log10(p.mean())


def true_peak_db(x):
    up = resample_poly(x, 4, 1, axis=1)
    return 20 * np.log10(np.max(np.abs(up)) + 1e-20)


def compressor(x, thr_db=-20, ratio=2.0, att=0.015, rel=0.2, knee=6.0):
    hop = 48
    n = x.shape[1] // hop
    blk = x[:, : n * hop].reshape(2, n, hop)
    lev = 10 * np.log10(np.mean(blk ** 2, axis=(0, 2)) + 1e-12)
    a_c, r_c = math.exp(-hop / SR / att), math.exp(-hop / SR / rel)
    sm = np.empty(n)
    s = lev[0]
    for i in range(n):
        c = a_c if lev[i] > s else r_c
        s = c * s + (1 - c) * lev[i]
        sm[i] = s
    over = sm - thr_db
    gr = np.where(over <= -knee / 2, 0.0,
                  np.where(over >= knee / 2, over * (1 - 1 / ratio),
                           (1 - 1 / ratio) * (over + knee / 2) ** 2 / (2 * knee)))
    g = 10 ** (-gr / 20)
    gs = np.interp(np.arange(x.shape[1]), np.arange(n) * hop + hop / 2, g)
    return x * gs, float(gr.max())


def soft_clip(x, th=0.7):
    a = np.abs(x)
    y = np.where(a <= th, a, th + (1 - th) * np.tanh((a - th) / (1 - th)))
    return np.sign(x) * y


def limiter(x, ceiling_db=-1.3, look=0.004, rel=0.09):
    c = 10 ** (ceiling_db / 20)
    up = np.abs(resample_poly(x, 4, 1, axis=1)).max(axis=0)
    pk = up[: x.shape[1] * 4].reshape(-1, 4).max(axis=1)
    pk = np.maximum(pk, np.abs(x).max(axis=0))
    need = np.minimum(1.0, c / np.maximum(pk, 1e-9))
    Lk = int(look * SR)
    g1 = minimum_filter1d(need, size=2 * Lk + 1, mode="nearest")
    a = math.exp(-1 / (rel * SR))
    g2 = np.empty_like(g1)
    s = 1.0
    for i, v in enumerate(g1):
        s = v if v < s else a * s + (1 - a) * v
        g2[i] = s
    g3 = uniform_filter1d(g2, size=Lk + 1, mode="nearest")
    return x * g3, float(20 * np.log10(g3.min()))


