def T(bar: int, beat: float = 1.0) -> float:
    """Contract time of (bar, beat), both 1-based."""
    return (bar - 1) * BAR + (beat - 1) * BEAT


def S(t: float) -> int:
    return int(round(t * SR))


_PC = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def M(name: str) -> int:
    """'F#4' -> MIDI number."""
    pc = _PC[name[0]]
    i = 1
    while i < len(name) and name[i] in "#b":
        pc += 1 if name[i] == "#" else -1
        i += 1
    return 12 * (int(name[i:]) + 1) + pc


def mtof(m: float) -> float:
    return 440.0 * 2.0 ** ((m - 69) / 12.0)


def rng_for(*key) -> np.random.Generator:
    h = SEED
    for k in key:
        for ch in str(k):
            h = (h * 131 + ord(ch)) % (2**61 - 1)
    return np.random.default_rng(h)


def pan_gains(p: float):
    a = (np.clip(p, -1, 1) + 1) * np.pi / 4
    return math.cos(a) * math.sqrt(2) * 0.5 + 0.0, math.sin(a) * math.sqrt(2) * 0.5


def smoothstep(x):
    x = np.clip(x, 0.0, 1.0)
    return x * x * (3 - 2 * x)


def fade_edges(x, fin=0.002, fout=0.02):
    """Click-free start/end (raised cosine), in place, works on (..., L)."""
    L = x.shape[-1]
    a = min(int(fin * SR), L // 2)
    b = min(int(fout * SR), L // 2)
    if a > 0:
        x[..., :a] *= 0.5 - 0.5 * np.cos(np.pi * np.arange(a) / a)
    if b > 0:
        x[..., L - b:] *= 0.5 + 0.5 * np.cos(np.pi * np.arange(b) / b)
    return x


def lp(fc, order=2):
    return butter(order, min(fc, SR * 0.45) / (SR / 2), "low", output="sos")


def hp(fc, order=2):
    return butter(order, fc / (SR / 2), "high", output="sos")


def bp(f1, f2, order=2):
    return butter(order, [f1 / (SR / 2), min(f2, SR * 0.45) / (SR / 2)], "band", output="sos")


def peaking(f0, q, gain_db):
    """RBJ cookbook peaking EQ as one SOS section."""
    A = 10 ** (gain_db / 40)
    w = TWO_PI * f0 / SR
    al = math.sin(w) / (2 * q)
    b = [1 + al * A, -2 * math.cos(w), 1 - al * A]
    a = [1 + al / A, -2 * math.cos(w), 1 - al / A]
    return np.array([[b[0] / a[0], b[1] / a[0], b[2] / a[0], 1.0, a[1] / a[0], a[2] / a[0]]])


def shelf(f0, gain_db, kind="low", s=0.8):
    A = 10 ** (gain_db / 40)
    w = TWO_PI * f0 / SR
    al = math.sin(w) / 2 * math.sqrt((A + 1 / A) * (1 / s - 1) + 2)
    c = math.cos(w)
    if kind == "low":
        b0 = A * ((A + 1) - (A - 1) * c + 2 * math.sqrt(A) * al)
        b1 = 2 * A * ((A - 1) - (A + 1) * c)
        b2 = A * ((A + 1) - (A - 1) * c - 2 * math.sqrt(A) * al)
        a0 = (A + 1) + (A - 1) * c + 2 * math.sqrt(A) * al
        a1 = -2 * ((A - 1) + (A + 1) * c)
        a2 = (A + 1) + (A - 1) * c - 2 * math.sqrt(A) * al
    else:
        b0 = A * ((A + 1) + (A - 1) * c + 2 * math.sqrt(A) * al)
        b1 = -2 * A * ((A - 1) + (A + 1) * c)
        b2 = A * ((A + 1) + (A - 1) * c - 2 * math.sqrt(A) * al)
        a0 = (A + 1) - (A - 1) * c + 2 * math.sqrt(A) * al
        a1 = 2 * ((A - 1) - (A + 1) * c)
        a2 = (A + 1) - (A - 1) * c - 2 * math.sqrt(A) * al
    return np.array([[b0 / a0, b1 / a0, b2 / a0, 1.0, a1 / a0, a2 / a0]])


def filt(sos, x):
    return sosfilt(sos, x, axis=-1)


def polyblep_saw(freq, phase0=0.0):
    """Band-limited sawtooth (PolyBLEP) for a per-sample frequency array."""
    dt = np.asarray(freq, dtype=np.float64) / SR
    ph = (phase0 + np.cumsum(dt)) % 1.0
    y = 2.0 * ph - 1.0
    m = ph < dt
    t = ph[m] / dt[m]
    y[m] -= t + t - t * t - 1.0
    m = ph > 1.0 - dt
    t = (ph[m] - 1.0) / dt[m]
    y[m] -= t * t + t + t + 1.0
    return y


