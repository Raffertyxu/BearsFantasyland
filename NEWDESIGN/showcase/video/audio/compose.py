def compose():
    # ---- barlines / beats for the picture team
    for b in range(1, 19):
        event("bar", T(b), bar=b)

    # ---- PIANO -------------------------------------------------------------
    def pedal_end(t):          # sustain pedal changes with every chord
        for t0, t1, _ in SEGS:
            if t0 <= t + 1e-9 < t1:
                return t1 + 0.04
        return DUR

    # intro: solo theme, single notes (+ a soft low root on each downbeat)
    for (b, bt, d, n) in THEME:
        t0 = T(b, bt)
        v = 0.42 + (0.08 if bt == 1 else 0) + (0.05 if d >= 1.5 else 0)
        piano(t0, n, v, pedal_end(t0) - t0, record=("melody", {"bar": b, "beat": bt,
              "accent": bt == 1 or d >= 1.5, "section": "intro"}))
    for b in range(1, 5):
        root = M(V[chord_at(T(b))][0]) + 12
        piano(T(b), root, 0.30, BAR, tag="lh")
    # verse: theme answer + left hand root / fifth
    for (b, bt, d, n) in VERSE:
        t0 = T(b, bt)
        v = 0.48 + (0.08 if bt == 1 else 0) + (0.05 if d >= 1.5 else 0)
        piano(t0, n, v, pedal_end(t0) - t0, record=("melody", {"bar": b, "beat": bt,
              "accent": bt == 1 or d >= 1.5, "section": "verse"}))
    for b in range(5, 9):
        c = chord_at(T(b))
        root = M(V[c][0]) + 12
        piano(T(b), root, 0.36, BAR, tag="lh")
        piano(T(b, 3), root + 7, 0.30, BAR / 2, tag="lh")
        piano(T(b, 3), root + 12, 0.26, BAR / 2, tag="lh")

    # build: 8th-note ostinato, register climbing with the harmony
    OST = {9: ["G4", "D5", "B4", "D5"], 10: ["A4", "E5", "C#5", "E5"],
           11: ["B4", "F#5", "D5", "F#5"], 12: ["C#5", "A5", "E5", "A5"]}
    for b in range(9, 13):
        pat = OST[b]
        n8 = 8 if b < 12 else 4                         # bar 12 stops at the hit
        for k in range(n8):
            t0 = T(b) + k * BEAT / 2
            grow = (b - 9) / 3 + k / 32
            v = 0.30 + 0.20 * grow + (0.10 if k % 2 == 0 else 0)
            note = pat[k % 4]
            piano(t0, note, v, BEAT * 0.9, tag="ost", record=("ostinato", {"bar": b}))
            add("pluck", t0, pizz_note(M(note) - 12, 0.55 + 0.35 * grow,
                                       rng_for("pz", round(t0 * 1000))), p=0.35)

    # climax: theme in octaves + harmony, left hand octaves
    for (b, bt, d, n) in CLIMAX:
        t0 = T(b, bt)
        m = M(n)
        accent = bt == 1
        v = 0.72 + (0.12 if accent else 0) + (0.05 if d >= 1.5 else 0)
        hold = pedal_end(t0) - t0
        piano(t0, m + 12, v, hold, tag="cmU", record=("melody", {"bar": b, "beat": bt,
              "accent": True, "section": "climax", "octaves": True}))
        piano(t0, m, v * 0.85, hold, tag="cmL")
        if d >= 1:
            pcs = PCS[chord_at(t0)]
            inner = [x for x in range(m + 2, m + 11) if x % 12 in pcs]
            inner.sort(key=lambda x: abs(x - (m + 6)))
            for i, x in enumerate(inner[:2]):
                piano(t0, x, v * 0.6, hold, tag="cmH")
    for (t0, t1, c) in SEGS:
        if 30 <= t0 < 40:
            root = M(V[c][0])
            piano(t0, root + 12, 0.72, t1 - t0 + 0.05, tag="cmB")
            if t1 - t0 > BEAT * 3:
                tm = t0 + 2 * BEAT
                piano(tm, root + 19, 0.5, t1 - tm, tag="cmB")
                piano(tm, root + 24, 0.45, t1 - tm, tag="cmB")

    # resolve: final D chord at 40.0 (bass + top exact, inner voices rolled)
    final = [("D2", 0.0, 0.62), ("A2", 0.025, 0.45), ("D3", 0.05, 0.45), ("F#3", 0.075, 0.42),
             ("A3", 0.10, 0.42), ("D4", 0.125, 0.45), ("D5", 0.0, 0.6)]
    for n, off, v in final:
        piano(40.0 + off, n, v, 5.0, tag="fin",
              record=("melody", {"bar": 17, "beat": 1, "accent": True, "section": "resolve"})
              if n == "D5" else (("chordRoll", {"bar": 17}) if off > 0 else None))
    piano(T(18), "A4", 0.30, 2.5, tag="echo",
          record=("melody", {"bar": 18, "beat": 1, "accent": False, "section": "resolve"}))
    piano(T(18, 2), "F#5", 0.32, 2.0, tag="echo",
          record=("melody", {"bar": 18, "beat": 2, "accent": False, "section": "resolve"}))

    # ---- PAD (air) --------------------------------------------------------
    for (t0, t1, c) in SEGS:
        if t0 >= DROP - 1.5 and t0 < DROP:          # bar 12 pad stops at the hit
            pass
        bass_n, up = V[c]
        if t0 < 10:
            vel, cut = 0.30, 800
        elif t0 < 20:
            vel, cut = 0.32, 900
        elif t0 < 30:
            vel, cut = 0.30 + 0.03 * (t0 - 20) / 2.5, 1000 + 120 * (t0 - 20) / 2.5
        elif t0 < 40:
            vel, cut = 0.36, 1300
        else:
            vel, cut = 0.34, 850
        end = min(t1, PRE_HIT + 0.1) if t0 < DROP else t1
        dur = end - t0
        if t0 >= 40:
            if t0 > 40:
                continue
            dur = 3.0
        for n in up:
            pad(t0, n, dur + 0.15, vel, cutoff=cut, att=1.2 if t0 > 0 else 1.8,
                rel=1.4 if t0 < 40 else 2.4)
        if t0 >= 30 and t0 < 40:
            pad(t0, up[-1][:-1] + str(int(up[-1][-1]) + 1), dur + 0.15, vel * 0.6, cutoff=cut)

    # ---- STRINGS ----------------------------------------------------------
    for (t0, t1, c) in SEGS:
        bass_n, up = V[c]
        bm = M(bass_n)
        dur = t1 - t0
        if 10 <= t0 < 20:              # verse: low strings enter
            v = 0.36 + 0.04 * (t0 - 10) / 2.5
            strings("cb", t0, bm, dur, v, att=0.6)
            strings("vc", t0, bm + 12, dur, v, att=0.6)
            strings("vla", t0, up[0], dur, v * 0.8, att=0.8)
            strings("vla", t0, up[1], dur, v * 0.8, att=0.8)
        elif 20 <= t0 < 30:            # build: everybody, crescendo, stop at the hit
            v = 0.42 + 0.07 * (t0 - 20) / 2.5
            d = min(dur, PRE_HIT + 0.08 - t0)
            strings("cb", t0, bm, d, v, att=0.35, rel=0.12)
            strings("vc", t0, bm + 12, d, v, att=0.35, rel=0.12)
            strings("vla", t0, up[0], d, v * 0.85, att=0.5, rel=0.12)
            strings("vla", t0, up[1], d, v * 0.85, att=0.5, rel=0.12)
            strings("vln2", t0, up[2], d, v * 0.8, att=0.6, rel=0.12)
        elif 30 <= t0 < 40:            # climax: full section
            v = 0.78
            strings("cb", t0, bm, dur, v, att=0.06, rel=0.6)
            strings("vc", t0, bm + 12, dur, v, att=0.06, rel=0.6)
            strings("vla", t0, up[0], dur, v * 0.85, att=0.12)
            strings("vla", t0, up[1], dur, v * 0.85, att=0.12)
            strings("vln2", t0, up[2], dur, v * 0.8, att=0.12)
            strings("vln2", t0, M(up[2]) + 12, dur, v * 0.55, att=0.15)
    # build: violins I rising line B4 C#5 D5 E5 (tenths over the climbing bass)
    for b, n in zip(range(9, 13), ["B4", "C#5", "D5", "E5"]):
        d = BAR if b < 12 else PRE_HIT + 0.08 - T(b)
        strings("vln1", T(b), n, d, 0.42 + 0.08 * (b - 9), att=0.7 if b == 9 else 0.3, rel=0.12)
    # climax: violins I carry the melody (legato)
    for i, (b, bt, d, n) in enumerate(CLIMAX):
        t0 = T(b, bt)
        strings("vln1", t0, n, d * BEAT + 0.08, 0.72, att=0.07, rel=0.35)
    # resolve: quiet cello/viola D chord under the piano (fades with the pad)
    strings("vc", 40.0, "D3", 2.6, 0.30, att=0.3, rel=1.8)
    strings("vla", 40.0, "A3", 2.6, 0.25, att=0.4, rel=1.8)

    # ---- BRASS (climax) ---------------------------------------------------
    for (t0, t1, c) in SEGS:
        if 30 <= t0 < 40:
            bass_n, up = V[c]
            dur = t1 - t0
            brass(t0, M_name(M(bass_n) + 12), dur, 0.75, p=-0.1)
            brass(t0, up[0], dur, 0.6, p=0.15)
            brass(t0, up[1], dur, 0.55, p=-0.2)

    # ---- SUB / BASS -------------------------------------------------------
    for (t0, t1, c) in SEGS:
        bn = V[c][0]
        if 10 <= t0 < 20:                    # warm pulse on beats 1 & 3
            for k in (0, 2):
                sub(t0 + k * BEAT, bn, BEAT * 1.8, 0.75, decay=0.5, sustain=0.35)
        elif 20 <= t0 < 30:
            beats = (0, 2) if t0 < 25 else (0, 1, 2, 3)
            for k in beats:
                tt = t0 + k * BEAT
                if tt < PRE_HIT:
                    sub(tt, bn, min(BEAT * (1.8 if len(beats) == 2 else 0.9), PRE_HIT + 0.05 - tt),
                        0.8, decay=0.4, sustain=0.35)
        elif 30 <= t0 < 40:
            sub(t0, bn, t1 - t0, 0.95, decay=0.8, sustain=0.6)
    sub(40.0, "D2", 3.5, 0.65, att=0.02, decay=1.2, sustain=0.0, rel=1.0)

    # ---- PERCUSSION -------------------------------------------------------
    # bar 10: toms on 1, 3 and the "and" of 4
    # (all drums are tuned to notes of D major)
    for tt, pitch, v, p in [(T(10, 1), DP("E2"), 0.55, -0.2), (T(10, 3), DP("F#2"), 0.5, 0.2),
                            (T(10, 4.5), DP("A2"), 0.45, 0.3)]:
        hit(tt, "tom", v, pitch, 0.7, p=p)
    # bar 11: every beat + pickup
    for k, tt in enumerate([T(11, 1), T(11, 2), T(11, 3), T(11, 4), T(11, 4.5)]):
        hit(tt, "tom", 0.55 + 0.05 * k, DP(["D2", "F#2", "E2", "A2", "B2"][k]), 0.7, p=[-.3, .25, -.15, .3, .1][k])
    hit(T(11, 1), "taiko", 0.6, DP("B1"), 1.0, p=0.0)
    # bar 12: 16th roll crescendo into the pre-drop hit
    for k in range(8):
        tt = T(12) + k * BEAT / 4
        hit(tt, "tom", 0.45 + 0.06 * k, DP(["E2", "F#2", "A2", "B2"][k % 4]), 0.55, p=-0.35 + 0.1 * k)
    # pre-drop hit (beat 3 of bar 12)
    hit(PRE_HIT, "taiko", 0.95, DP("A1"), 1.3)
    impact(PRE_HIT, "preDropHit", size=0.8, gain=0.8)
    # climax: taiko on every beat, impact on every downbeat
    for k in range(16):
        tt = DROP + k * BEAT
        down = k % 4 == 0
        hit(tt, "taiko", 0.95 if down else 0.72 + 0.04 * (k % 2), bass_hz(tt) / 60.0,
            1.25 if down else 0.9, p=0.0 if down else (-0.15 if k % 2 else 0.15),
            gain=1.0 if down else 0.8)
        if not down:   # light 8th-note ghost on the off-beat for drive
            hit(tt + BEAT / 2, "tomGhost", 0.32, 2 * bass_hz(tt) / 60.0, 0.45, p=0.3 if k % 2 else -0.3,
                gain=0.55, slap=1.4)
    impact(DROP, "DROP", size=1.25, gain=1.1)
    for b in (14, 15, 16):
        impact(T(b), "downbeatImpact", size=0.75, gain=0.55)
    impact(40.0, "resolveBoom", size=0.7, gain=0.28)
    # climax pizz ostinato keeps the 8th-note motion going
    for (t0, t1, c) in SEGS:
        if 30 <= t0 < 40:
            bass_n, up = V[c]
            pat = [M(up[0]) + 12, M(up[2]) + 12, M(up[1]) + 12, M(up[2]) + 12]
            k = 0
            while t0 + k * BEAT / 2 < t1 - 1e-6:
                tt = t0 + k * BEAT / 2
                add("pluck", tt, pizz_note(pat[k % 4], 0.75 + (0.15 if k % 2 == 0 else 0),
                                           rng_for("pzc", round(tt * 1000))), p=0.35)
                k += 1

    # ---- FX ---------------------------------------------------------------
    rr = rng_for("riser")
    rs = riser_sig(PRE_HIT - T(11), rr)
    add("fx", T(11), rs, gain=0.55)
    event("riser", T(11), end=PRE_HIT)
    # reverse cymbal into the pre-drop hit
    cy = cymbal(2.5, rng_for("cy-rev"), decay=1.4)[:, ::-1].copy()
    cy *= np.linspace(0, 1, cy.shape[1]) ** 1.5
    add("fx", PRE_HIT - 2.5, fade_edges(cy, 0.05, 0.002), gain=0.30)
    # DROP: crash + cymbal swell resolving into the downbeat ring
    add("fx", DROP, cymbal(4.5, rng_for("crash"), decay=2.2), gain=0.42)
    event("crash", DROP)
    add("fx", T(15), cymbal(3.5, rng_for("crash2"), decay=1.8), gain=0.22)
    event("crash", T(15))
    # cymbal roll swell into the resolve (bar 16 beats 3-4), soft crash at 40
    sw = cymbal(1.25, rng_for("swell"), decay=1.0)[:, ::-1].copy()
    sw *= np.linspace(0, 1, sw.shape[1]) ** 2
    add("fx", 40.0 - 1.25, fade_edges(sw, 0.05, 0.002), gain=0.20)
    add("fx", 40.0, cymbal(4.0, rng_for("crash3"), decay=2.4), gain=0.14)


def M_name(m):
    names = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
    return f"{names[m % 12]}{m // 12 - 1}"


