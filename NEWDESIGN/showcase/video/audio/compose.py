def check_voice_leading():
    """Report parallel perfect 5ths / octaves between any two voices."""
    seq = [c for _, _, c in SEGS]
    problems = []
    for a, b in zip(seq, seq[1:]):
        if a == b:
            continue
        va = [M(V[a][0])] + [M(x) for x in V[a][1]]
        vb = [M(V[b][0])] + [M(x) for x in V[b][1]]
        for i in range(4):
            for j in range(i + 1, 4):
                ia, ib = (va[j] - va[i]) % 12, (vb[j] - vb[i]) % 12
                moved = va[i] != vb[i] or va[j] != vb[j]
                same_dir = np.sign(vb[i] - va[i]) == np.sign(vb[j] - va[j]) != 0
                if moved and same_dir and ia == ib and ia in (0, 7):
                    problems.append(f"{a}->{b} voices {i},{j} parallel {'8ve' if ia == 0 else '5th'}")
    return problems


