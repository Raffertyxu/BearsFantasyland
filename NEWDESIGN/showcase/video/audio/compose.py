def brass_note(midi, dur, vel, rng, att=0.22, rel=0.7):
    """Low brass pad: drive saws, swelling low-pass, vowel-like formants."""
    f0 = mtof(midi)
    L = int((dur + rel + 0.05) * SR)
    t = np.arange(L) / SR
    x = np.zeros(L)
    for v in range(3):
        c = (v - 1) * 4.5 + 2.5 * np.sin(TWO_PI * rng.uniform(0.15, 0.4) * t + rng.random() * 6)
        x += polyblep_saw(f0 * 2 ** (c / 1200), rng.random())
    x = np.tanh(1.6 * x / 3) / np.tanh(1.6)
    blat = 0.35 + 0.65 * (1 - np.exp(-t / 0.28))
    dark, bright = filt(lp(380, 4), x), filt(lp(1900, 4), x)
    y = dark + (bright - dark) * (blat * vel)
    y = filt(peaking(520, 1.4, 6.0), y)
    y = filt(peaking(1150, 2.2, 3.5), y)
    y = filt(peaking(2600, 1.5, -5.0), y)
    y = filt(hp(65), y)
    env = smoothstep(t / att) * (0.5 + 0.5 * np.cos(np.pi * np.clip((t - dur) / rel, 0, 1)))
    return fade_edges(y * env * vel, 0.004, 0.04)


