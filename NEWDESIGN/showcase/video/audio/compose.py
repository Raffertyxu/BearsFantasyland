def pad_note(midi, dur, vel, rng, att=1.6, rel=1.8, cutoff=950):
    f0 = mtof(midi)
    L = int((dur + rel + 0.05) * SR)
    t = np.arange(L) / SR
    out = np.zeros((2, L))
    for v in range(4):
        x = (v / 3) * 2 - 1
        c = x * 11 + 3 * np.sin(TWO_PI * rng.uniform(0.1, 0.25) * t + rng.random() * 6.3)
        saw = polyblep_saw(f0 * 2 ** (c / 1200), rng.random())
        gl, gr = pan_gains(x * 0.7)
        out[0] += saw * gl
        out[1] += saw * gr
    tri = np.abs(((np.arange(L) * f0 / SR) % 1.0) * 4 - 2) - 1   # soft fundamental
    out += 0.35 * tri
    out = filt(lp(cutoff, 4), out) * 0.5
    # breathy air layer (kept low and below the harsh band)
    air = filt(bp(700, 2200), rng.standard_normal((2, L))) * 0.05
    air *= 0.6 + 0.4 * np.sin(TWO_PI * 0.23 * t + rng.random() * 6)
    out += air
    env = smoothstep(t / att) * (0.5 + 0.5 * np.cos(np.pi * np.clip((t - dur) / rel, 0, 1)))
    return fade_edges(filt(hp(110), out) * env * vel, 0.01, 0.05)


